begin;

-- 1. TABELA DE SÓCIOS
create table if not exists public.financeiro_socios (
  id bigint generated by default as identity primary key,
  nome text not null,
  cpf text,
  email text,
  telefone text,
  participacao_percentual numeric(5,2) not null default 0 check (participacao_percentual >= 0 and participacao_percentual <= 100),
  data_entrada date not null default current_date,
  status text not null default 'Ativo' check (status in ('Ativo', 'Inativo')),
  observacao text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index if not exists idx_financeiro_socios_status on public.financeiro_socios(status);

-- 2. TABELA DE APORTES DOS SÓCIOS
create table if not exists public.financeiro_aportes (
  id bigint generated by default as identity primary key,
  socio_id bigint not null references public.financeiro_socios(id) on delete restrict,
  valor numeric(12,2) not null check (valor > 0),
  data date not null default current_date,
  forma_pagamento text not null default 'Pix' check (forma_pagamento in ('Pix', 'Transferência', 'Dinheiro', 'Depósito', 'Outro')),
  observacao text,
  criado_em timestamptz not null default now()
);

create index if not exists idx_financeiro_aportes_socio on public.financeiro_aportes(socio_id);
create index if not exists idx_financeiro_aportes_data on public.financeiro_aportes(data desc);

-- 3. TABELA DE RETIRADAS DOS SÓCIOS
create table if not exists public.financeiro_retiradas (
  id bigint generated by default as identity primary key,
  socio_id bigint not null references public.financeiro_socios(id) on delete restrict,
  valor numeric(12,2) not null check (valor > 0),
  data date not null default current_date,
  tipo text not null default 'Distribuição de lucro' check (tipo in ('Distribuição de lucro', 'Retirada', 'Reembolso', 'Pró-labore', 'Outros')),
  forma_pagamento text not null default 'Pix',
  observacao text,
  criado_em timestamptz not null default now()
);

create index if not exists idx_financeiro_retiradas_socio on public.financeiro_retiradas(socio_id);
create index if not exists idx_financeiro_retiradas_data on public.financeiro_retiradas(data desc);

-- 4. TABELA DE CATEGORIAS DE DESPESAS
create table if not exists public.financeiro_categorias_despesa (
  id bigint generated by default as identity primary key,
  nome text not null unique,
